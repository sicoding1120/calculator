export const penjumlahan = (a:number, b:number) => {
    const hasil = a + b;
    return hasil;
}

export const pengurangan = (a:number, b:number) => {
    const hasil = a - b;
    return hasil;
}

export const perkalian = (a:number, b:number) => {
    const hasil = a * b;
    return hasil;
}

export const pembagian = (a:number, b:number) => {
    const hasil = a / b;
    return hasil;
}
